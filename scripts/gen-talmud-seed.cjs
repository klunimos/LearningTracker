const q = (s) => "N'" + String(s).replace(/'/g, "''") + "'";

// Build per-masechet (book + amud rows) and tally totals.
let totalUnits = 0;
let bookOrder = 0; // Books.SortOrder — array is already in canonical Shas order
const blocks = [];
const summary = [];

for (const [name, seder, length] of MASECHTOT) {
  bookOrder++;
  const lastDaf = Math.ceil(length / 2);
  const endsOnAmudA = (length % 2) === 1; // odd length -> last daf has only ע"א
  const rows = [];
  let sort = 0;   // SortOrder: running unit index within the book (1..N)
  let dafIdx = 0; // L1Order: running daf-group index within the book (1..lastDaf-1)
  for (let daf = 2; daf <= lastDaf; daf++) {
    dafIdx++;
    const heb = gematria(daf);
    const groupLabel = `דף ${heb}`;
    // The last daf of some masechtot has only amud alef (no ע"ב); its group holds one unit.
    const amudim = (daf === lastDaf && endsOnAmudA) ? ['ע"א'] : ['ע"א', 'ע"ב'];
    let amudIdx = 0; // UnitOrder: position within the daf group (1 or 2)
    for (const amud of amudim) {
      sort++; amudIdx++;
      const unitLabel = `${heb} ${amud}`;
      const displayName = `${name} ${heb} ${amud}`;
      rows.push(`  (@bookId, ${q(groupLabel)}, ${dafIdx}, ${q(unitLabel)}, ${amudIdx}, ${q(displayName)}, ${sort})`);
    }
  }
  const i = sort;
  totalUnits += i;
  summary.push(`--   ${seder.padEnd(11)} | ${name.padEnd(12)} | dapim 2-${lastDaf} | ${i} amudim`);

  blocks.push(
`    -- ${name} (${seder}) — ${i} amudim
    INSERT INTO dbo.Books (CategoryId, Name, SeriesName, SortOrder, CreatedByUserId)
    VALUES (@catId, ${q(name)}, ${q(seder)}, ${bookOrder}, @uid);
    SET @bookId = SCOPE_IDENTITY();
    INSERT INTO dbo.BookUnits (BookId, L1Label, L1Order, UnitLabel, UnitOrder, DisplayName, SortOrder) VALUES
${rows.join(',\n')};
`);
}

const header =
`-- scripts/2026-06-17_seed-talmud-bavli.sql
-- Target: LearningTracker
-- Seeds the entire Talmud Bavli as a content catalog.
--   Category "תלמוד בבלי"  ->  ${MASECHTOT.length} Books (masechtot)  ->  ${totalUnits} BookUnits (amudim)
--
-- Structure source: Sefaria api/shape/Talmud (Vilna). One unit per amud
-- (ע"א / ע"ב); each masechet runs from daf 2a to its last daf. Shekalim is
-- excluded (it has no Bavli gemara). Units are grouped by daf: L1Label =
-- "דף <n>", each holding its ע"א/ע"ב (some masechtot' last daf has only ע"א).
-- Category (SortOrder 1) and Books (SortOrder 1..37 in canonical Shas order)
-- need the columns from scripts/2026-06-17_catalog-sortorder.sql, applied first.
--
-- GENERATED by scripts/gen-talmud-seed.cjs — do not hand-edit; regenerate.
-- Idempotent: skips entirely if the category already exists. Transactional.
--
-- Breakdown:
${summary.join('\n')}
-- ============================================================

USE [LearningTracker];
GO

SET QUOTED_IDENTIFIER ON;
SET NOCOUNT ON;
GO

IF NOT EXISTS (SELECT 1 FROM dbo.Categories WHERE Name = N'תלמוד בבלי')
BEGIN
  BEGIN TRY
    BEGIN TRAN;

    -- Attribute the content to an admin user (fall back to the known owner email).
    DECLARE @uid INT =
        COALESCE(
            (SELECT TOP 1 Id FROM dbo.Users WHERE IsAdmin = 1 ORDER BY Id),
            (SELECT TOP 1 Id FROM dbo.Users WHERE Email = N'israel@haravdotnet.co.il'));
    IF @uid IS NULL
        THROW 50001, 'No admin user found to own the Talmud catalog. Create one first, then re-run.', 1;

    DECLARE @catId INT, @bookId INT;

    INSERT INTO dbo.Categories (Name, L1Name, L2Name, UnitName, SortOrder, CreatedByUserId)
    VALUES (N'תלמוד בבלי', N'מסכת', N'פרק', N'עמוד', 1, @uid);
    SET @catId = SCOPE_IDENTITY();

`;

const footer =
`
    COMMIT TRAN;
    PRINT 'Talmud Bavli seeded: 1 category, ${MASECHTOT.length} books, ${totalUnits} units.';
  END TRY
  BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRAN;
    THROW;
  END CATCH
END
ELSE
    PRINT 'Talmud Bavli already seeded (category exists) — skipping.';
GO
`;

const sql = header + blocks.join('\n') + footer;
const outPath = path.join(__dirname, '2026-06-17_seed-talmud-bavli.sql');
fs.writeFileSync(outPath, sql, 'utf8'); // UTF-8, no BOM (run sqlcmd with -f 65001)

console.log(`Wrote ${outPath}`);
