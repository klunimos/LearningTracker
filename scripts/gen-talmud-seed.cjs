/*
 * Generates an idempotent SQL seed script for the entire Talmud Bavli.
 *
 *   node scripts/gen-talmud-seed.cjs
 *     -> writes scripts/2026-06-17_seed-talmud-bavli.sql
 *
 * Source of structure: Sefaria api/shape/Talmud. Sefaria's `length` counts
 * amudim including a phantom title-daf, so:  lastDaf = ceil(length/2),
 * and a masechet ends on amud alef (no ע"ב on the last daf) iff length is odd.
 * Every masechet starts at daf 2 (2a). Units are emitted at AMUD resolution.
 */
const fs = require('fs');
const path = require('path');

// --- Hebrew gematria for daf numbers (handles 15/16 = טו/טז) ---
const ONES = ['', 'א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט'];
const TENS = ['', 'י', 'כ', 'ל', 'מ', 'נ', 'ס', 'ע', 'פ', 'צ'];
const HUNDREDS = ['', 'ק', 'ר', 'ש', 'ת', 'תק', 'תר', 'תש', 'תת', 'תתק'];

function gematria(n) {
  let out = HUNDREDS[Math.floor(n / 100)];
  const rem = n % 100;
  if (rem === 15) out += 'טו';
  else if (rem === 16) out += 'טז';
  else out += TENS[Math.floor(rem / 10)] + ONES[rem % 10];
  return out;
}

// title (Hebrew), seder, Sefaria length (= amudim incl. phantom daf)
